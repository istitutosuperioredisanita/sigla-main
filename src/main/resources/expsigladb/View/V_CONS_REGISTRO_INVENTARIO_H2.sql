-- SIGLASVILUPPO.V_CONS_REGISTRO_INVENTARIO
-- Versione con OUTER JOIN: INVENTARIO_BENI e' la tabella driver, i movimenti
-- (BUONO_CARICO_SCARICO_DETT, BUONO_CARICO_SCARICO, TIPO_CARICO_SCARICO) sono opzionali.
-- Se il movimento non esiste i valori vengono ricavati da INVENTARIO_BENI.

CREATE OR REPLACE FORCE VIEW "V_CONS_REGISTRO_INVENTARIO" (
    "PG_INVENTARIO",
    "TI_DOCUMENTO",
    "ESERCIZIO",
    "PG_BUONO_C_S",
    "NR_INVENTARIO",
    "PROGRESSIVO",
    "CD_UNITA_ORGANIZZATIVA",
    "CD_CDS",
    "ESERCIZIO_CARICO_BENE",
    "ETICHETTA",
    "DS_BENE",
    "FL_TOTALMENTE_SCARICATO",
    "FL_DISMESSO",
    "DT_DISMESSO",
    "FL_BENE_IN_IST",
    "FL_MIGRATO",
    "VALORE_INIZIALE",
    "CATEGORIA",
    "CD_CATEGORIA_GRUPPO",
    "DS_CATEGORIA_GRUPPO",
    "DS_UBICAZIONE_BENE",
    "CD_ASSEGNATARIO",
    "DENOMINAZIONE_SEDE",
    "DATA_REGISTRAZIONE",
    "CD_TIPO_CARICO_SCARICO",
    "DS_TIPO_CARICO_SCARICO",
    "VARIAZIONE_PIU",
    "VARIAZIONE_MENO",
    "QUANTITA",
    "VALORE_UNITARIO",
    "IMPONIBILE_AMMORTAMENTO",
    "VALORE_AMMORTIZZATO",
    "IM_MOVIMENTO_AMMORT",
    "NUMERO_ANNI",
    "PERC_AMMORTAMENTO",
    "PERC_PRIMO_ANNO",
    "PERC_SUCCESSIVI",
    "CD_UTILIZZATORE_CDR",
    "CD_LINEA_ATTIVITA",
    "PERCENTUALE_UTILIZZO_CDR",
    "PERCENTUALE_UTILIZZO_LA",
    "ESERCIZIO_AMM",
    "CD_UNITA_ASSEGNATARIO"
) AS SELECT
    INVENTARIO_BENI.PG_INVENTARIO,
    -- se manca il movimento il bene e' comunque stato caricato: tipo documento 'C'
    NVL(BUONO_CARICO_SCARICO_DETT.TI_DOCUMENTO, 'C')                          TI_DOCUMENTO,
    NVL(BUONO_CARICO_SCARICO_DETT.ESERCIZIO, INVENTARIO_BENI.ESERCIZIO_CARICO_BENE) ESERCIZIO,
    BUONO_CARICO_SCARICO_DETT.PG_BUONO_C_S,                                   -- NULL se nessun buono
    INVENTARIO_BENI.NR_INVENTARIO,
    INVENTARIO_BENI.PROGRESSIVO,
    INVENTARIO_BENI.CD_UNITA_ORGANIZZATIVA,
    INVENTARIO_BENI.CD_CDS,
    INVENTARIO_BENI.ESERCIZIO_CARICO_BENE,
    INVENTARIO_BENI.ETICHETTA,
    INVENTARIO_BENI.DS_BENE,
    INVENTARIO_BENI.FL_TOTALMENTE_SCARICATO,
    INVENTARIO_BENI.FL_DISMESSO,
    INVENTARIO_BENI.DT_DISMESSO,
    INVENTARIO_BENI.FL_BENE_IN_IST,
    INVENTARIO_BENI.FL_MIGRATO,
    -- VALORE_INIZIALE
    CASE
      WHEN BUONO_CARICO_SCARICO_DETT.PG_BUONO_C_S IS NULL
        THEN INVENTARIO_BENI.VALORE_INIZIALE
      WHEN BUONO_CARICO_SCARICO_DETT.TI_DOCUMENTO = 'C'
       AND BUONO_CARICO_SCARICO_DETT.PG_BUONO_C_S =
           (SELECT MIN(dett.PG_BUONO_C_S)
              FROM BUONO_CARICO_SCARICO_DETT dett
             WHERE dett.TI_DOCUMENTO = 'C'
               AND dett.PG_INVENTARIO = INVENTARIO_BENI.PG_INVENTARIO
               AND dett.NR_INVENTARIO = INVENTARIO_BENI.NR_INVENTARIO
               AND dett.PROGRESSIVO   = INVENTARIO_BENI.PROGRESSIVO
               AND dett.ESERCIZIO     = BUONO_CARICO_SCARICO_DETT.ESERCIZIO
               AND dett.ESERCIZIO     = (SELECT MIN(dett2.ESERCIZIO)
                                           FROM BUONO_CARICO_SCARICO_DETT dett2
                                          WHERE dett2.PG_INVENTARIO = dett.PG_INVENTARIO
                                            AND dett2.NR_INVENTARIO = dett.NR_INVENTARIO
                                            AND dett2.PROGRESSIVO   = dett.PROGRESSIVO
                                            AND dett2.TI_DOCUMENTO  = dett.TI_DOCUMENTO))
        THEN BUONO_CARICO_SCARICO_DETT.VALORE_UNITARIO
      ELSE 0
    END                                                                        VALORE_INIZIALE,
    CATEGORIA_GRUPPO_INVENT.CD_CATEGORIA_PADRE                                 CATEGORIA,
    INVENTARIO_BENI.CD_CATEGORIA_GRUPPO,
    CATEGORIA_GRUPPO_INVENT.DS_CATEGORIA_GRUPPO,
    UBICAZIONE_BENE.DS_UBICAZIONE_BENE,
    INVENTARIO_BENI.CD_ASSEGNATARIO,
    TERZO.DENOMINAZIONE_SEDE,
    -- DATA_REGISTRAZIONE: se non c'e' il buono si usa la data di acquisizione del bene
    NVL(BUONO_CARICO_SCARICO.DATA_REGISTRAZIONE, INVENTARIO_BENI.DT_ACQUISIZIONE) DATA_REGISTRAZIONE,
    TIPO_CARICO_SCARICO.CD_TIPO_CARICO_SCARICO,
    TIPO_CARICO_SCARICO.DS_TIPO_CARICO_SCARICO,
    -- VARIAZIONE_PIU
    CASE
      WHEN BUONO_CARICO_SCARICO_DETT.PG_BUONO_C_S IS NULL
        THEN NVL(INVENTARIO_BENI.VARIAZIONE_PIU, 0)
      WHEN BUONO_CARICO_SCARICO_DETT.PG_BUONO_C_S =
           (SELECT MIN(dett.PG_BUONO_C_S)
              FROM BUONO_CARICO_SCARICO_DETT dett
             WHERE dett.TI_DOCUMENTO = 'C'
               AND dett.PG_INVENTARIO = INVENTARIO_BENI.PG_INVENTARIO
               AND dett.NR_INVENTARIO = INVENTARIO_BENI.NR_INVENTARIO
               AND dett.PROGRESSIVO   = INVENTARIO_BENI.PROGRESSIVO
               AND dett.ESERCIZIO     = BUONO_CARICO_SCARICO_DETT.ESERCIZIO
               AND dett.ESERCIZIO     = (SELECT MIN(dett2.ESERCIZIO)
                                           FROM BUONO_CARICO_SCARICO_DETT dett2
                                          WHERE dett2.PG_INVENTARIO = dett.PG_INVENTARIO
                                            AND dett2.NR_INVENTARIO = dett.NR_INVENTARIO
                                            AND dett2.PROGRESSIVO   = dett.PROGRESSIVO
                                            AND dett2.TI_DOCUMENTO  = dett.TI_DOCUMENTO))
        THEN 0
      WHEN BUONO_CARICO_SCARICO_DETT.TI_DOCUMENTO = 'C'
        THEN BUONO_CARICO_SCARICO_DETT.VALORE_UNITARIO
      ELSE 0
    END                                                                        VARIAZIONE_PIU,
    -- VARIAZIONE_MENO
    CASE
      WHEN BUONO_CARICO_SCARICO_DETT.PG_BUONO_C_S IS NULL
        THEN NVL(INVENTARIO_BENI.VARIAZIONE_MENO, 0)
      WHEN BUONO_CARICO_SCARICO_DETT.TI_DOCUMENTO = 'S'
        THEN BUONO_CARICO_SCARICO_DETT.VALORE_UNITARIO
      ELSE 0
    END                                                                        VARIAZIONE_MENO,
    BUONO_CARICO_SCARICO_DETT.QUANTITA,
    NVL(BUONO_CARICO_SCARICO_DETT.VALORE_UNITARIO, INVENTARIO_BENI.VALORE_INIZIALE) VALORE_UNITARIO,
    NVL(INVENTARIO_BENI.IMPONIBILE_AMMORTAMENTO, 0)                            IMPONIBILE_AMMORTAMENTO,
    INVENTARIO_BENI.VALORE_AMMORTIZZATO,
    (NVL(AMMORTAMENTO_BENE_INV.IM_MOVIMENTO_AMMORT, 0)
       * NVL(INVENTARIO_UTILIZZATORI_LA.PERCENTUALE_UTILIZZO_CDR, 100) / 100
       * NVL(INVENTARIO_UTILIZZATORI_LA.PERCENTUALE_UTILIZZO_LA, 100) / 100)   IM_MOVIMENTO_AMMORT,
    AMMORTAMENTO_BENE_INV.NUMERO_ANNI,
    AMMORTAMENTO_BENE_INV.PERC_AMMORTAMENTO,
    AMMORTAMENTO_BENE_INV.PERC_PRIMO_ANNO,
    AMMORTAMENTO_BENE_INV.PERC_SUCCESSIVI,
    INVENTARIO_UTILIZZATORI_LA.CD_UTILIZZATORE_CDR,
    INVENTARIO_UTILIZZATORI_LA.CD_LINEA_ATTIVITA,
    INVENTARIO_UTILIZZATORI_LA.PERCENTUALE_UTILIZZO_CDR,
    INVENTARIO_UTILIZZATORI_LA.PERCENTUALE_UTILIZZO_LA,
    AMMORTAMENTO_BENE_INV.ESERCIZIO                                            ESERCIZIO_AMM,
    ANAGRAFICO_ASSEGNATARIO.CD_UNITA_ORGANIZZATIVA                             CD_UNITA_ASSEGNATARIO
FROM INVENTARIO_BENI
     JOIN UBICAZIONE_BENE
       ON  UBICAZIONE_BENE.CD_CDS                  = INVENTARIO_BENI.CD_CDS
       AND UBICAZIONE_BENE.CD_UNITA_ORGANIZZATIVA  = INVENTARIO_BENI.CD_UNITA_ORGANIZZATIVA
       AND UBICAZIONE_BENE.CD_UBICAZIONE           = INVENTARIO_BENI.CD_UBICAZIONE
     JOIN CATEGORIA_GRUPPO_INVENT
       ON  CATEGORIA_GRUPPO_INVENT.CD_CATEGORIA_GRUPPO = INVENTARIO_BENI.CD_CATEGORIA_GRUPPO
     JOIN TERZO
       ON  TERZO.CD_UNITA_ORGANIZZATIVA = INVENTARIO_BENI.CD_UNITA_ORGANIZZATIVA
       AND TERZO.CD_TERZO IN (SELECT MIN(t.CD_TERZO)
                                FROM TERZO t
                               WHERE t.CD_UNITA_ORGANIZZATIVA = INVENTARIO_BENI.CD_UNITA_ORGANIZZATIVA
                                 AND t.DT_FINE_RAPPORTO IS NULL)
     -- OUTER JOIN richiesto: movimenti di carico/scarico
     LEFT JOIN BUONO_CARICO_SCARICO_DETT
       ON  BUONO_CARICO_SCARICO_DETT.PG_INVENTARIO = INVENTARIO_BENI.PG_INVENTARIO
       AND BUONO_CARICO_SCARICO_DETT.NR_INVENTARIO = INVENTARIO_BENI.NR_INVENTARIO
       AND BUONO_CARICO_SCARICO_DETT.PROGRESSIVO   = INVENTARIO_BENI.PROGRESSIVO
     LEFT JOIN BUONO_CARICO_SCARICO
       ON  BUONO_CARICO_SCARICO.PG_INVENTARIO = BUONO_CARICO_SCARICO_DETT.PG_INVENTARIO
       AND BUONO_CARICO_SCARICO.TI_DOCUMENTO  = BUONO_CARICO_SCARICO_DETT.TI_DOCUMENTO
       AND BUONO_CARICO_SCARICO.ESERCIZIO     = BUONO_CARICO_SCARICO_DETT.ESERCIZIO
       AND BUONO_CARICO_SCARICO.PG_BUONO_C_S  = BUONO_CARICO_SCARICO_DETT.PG_BUONO_C_S
     LEFT JOIN TIPO_CARICO_SCARICO
       ON  TIPO_CARICO_SCARICO.CD_TIPO_CARICO_SCARICO = BUONO_CARICO_SCARICO.CD_TIPO_CARICO_SCARICO
     LEFT JOIN AMMORTAMENTO_BENE_INV
       ON  AMMORTAMENTO_BENE_INV.PG_INVENTARIO = INVENTARIO_BENI.PG_INVENTARIO
       AND AMMORTAMENTO_BENE_INV.NR_INVENTARIO = INVENTARIO_BENI.NR_INVENTARIO
       AND AMMORTAMENTO_BENE_INV.PROGRESSIVO   = INVENTARIO_BENI.PROGRESSIVO
     LEFT JOIN INVENTARIO_UTILIZZATORI_LA
       ON  INVENTARIO_UTILIZZATORI_LA.PG_INVENTARIO = INVENTARIO_BENI.PG_INVENTARIO
       AND INVENTARIO_UTILIZZATORI_LA.NR_INVENTARIO = INVENTARIO_BENI.NR_INVENTARIO
       AND INVENTARIO_UTILIZZATORI_LA.PROGRESSIVO   = INVENTARIO_BENI.PROGRESSIVO
     LEFT JOIN TERZO TERZO_ASSEGNATARIO
       ON  TERZO_ASSEGNATARIO.CD_TERZO = INVENTARIO_BENI.CD_ASSEGNATARIO
     LEFT JOIN ANAGRAFICO ANAGRAFICO_ASSEGNATARIO
       ON  ANAGRAFICO_ASSEGNATARIO.CD_ANAG = TERZO_ASSEGNATARIO.CD_ANAG;
