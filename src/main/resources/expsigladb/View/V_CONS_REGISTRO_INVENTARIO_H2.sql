-- SIGLASVILUPPO.V_CONS_REGISTRO_INVENTARIO
-- Versione con OUTER JOIN: INVENTARIO_BENI e' la tabella driver, i movimenti
-- (BUONO_CARICO_SCARICO_DETT, BUONO_CARICO_SCARICO, TIPO_CARICO_SCARICO) sono opzionali.
-- Se il movimento non esiste i valori vengono ricavati da INVENTARIO_BENI.

CREATE OR REPLACE FORCE VIEW "V_CONS_REGISTRO_INVENTARIO" (
    "PG_INVENTARIO",
    "TI_DOCUMENTO",
    "ESERCIZIO",
    "PG_BUONO_C_S",
    "NR_INVENTARIO",
    "PROGRESSIVO",
    "CD_UNITA_ORGANIZZATIVA",
    "CD_CDS",
    "ESERCIZIO_CARICO_BENE",
    "ETICHETTA",
    "DS_BENE",
    "FL_TOTALMENTE_SCARICATO",
    "FL_DISMESSO",
    "DT_DISMESSO",
    "FL_BENE_IN_IST",
    "FL_MIGRATO",
    "VALORE_INIZIALE",
    "CATEGORIA",
    "CD_CATEGORIA_GRUPPO",
    "DS_CATEGORIA_GRUPPO",
    "DS_UBICAZIONE_BENE",
    "CD_ASSEGNATARIO",
    "DENOMINAZIONE_SEDE",
    "DATA_REGISTRAZIONE",
    "CD_TIPO_CARICO_SCARICO",
    "DS_TIPO_CARICO_SCARICO",
    "VARIAZIONE_PIU",
    "VARIAZIONE_MENO",
    "QUANTITA",
    "VALORE_UNITARIO",
    "IMPONIBILE_AMMORTAMENTO",
    "VALORE_AMMORTIZZATO",
    "IM_MOVIMENTO_AMMORT",
    "NUMERO_ANNI",
    "PERC_AMMORTAMENTO",
    "PERC_PRIMO_ANNO",
    "PERC_SUCCESSIVI",
    "CD_UTILIZZATORE_CDR",
    "CD_LINEA_ATTIVITA",
    "PERCENTUALE_UTILIZZO_CDR",
    "PERCENTUALE_UTILIZZO_LA",
    "ESERCIZIO_AMM",
    "CD_UNITA_ASSEGNATARIO"
) AS SELECT
     V_CONS_REGISTRO_INVENTARIO_BENI.PG_INVENTARIO,
     V_CONS_REGISTRO_INVENTARIO_BENI.TI_DOCUMENTO,
     V_CONS_REGISTRO_INVENTARIO_BENI.ESERCIZIO,
     V_CONS_REGISTRO_INVENTARIO_BENI.PG_BUONO_C_S,
     V_CONS_REGISTRO_INVENTARIO_BENI.NR_INVENTARIO,
     V_CONS_REGISTRO_INVENTARIO_BENI.PROGRESSIVO,
     V_CONS_REGISTRO_INVENTARIO_BENI.CD_UNITA_ORGANIZZATIVA,
     V_CONS_REGISTRO_INVENTARIO_BENI.CD_CDS,
     V_CONS_REGISTRO_INVENTARIO_BENI.ESERCIZIO_CARICO_BENE,
     V_CONS_REGISTRO_INVENTARIO_BENI.ETICHETTA,
     V_CONS_REGISTRO_INVENTARIO_BENI.DS_BENE,
     V_CONS_REGISTRO_INVENTARIO_BENI.FL_TOTALMENTE_SCARICATO,
     V_CONS_REGISTRO_INVENTARIO_BENI.FL_DISMESSO,
     V_CONS_REGISTRO_INVENTARIO_BENI.DT_DISMESSO,
     V_CONS_REGISTRO_INVENTARIO_BENI.FL_BENE_IN_IST,
     V_CONS_REGISTRO_INVENTARIO_BENI.FL_MIGRATO,
     V_CONS_REGISTRO_INVENTARIO_BENI.VALORE_INIZIALE,
     V_CONS_REGISTRO_INVENTARIO_BENI.CATEGORIA,
     V_CONS_REGISTRO_INVENTARIO_BENI.CD_CATEGORIA_GRUPPO,
     V_CONS_REGISTRO_INVENTARIO_BENI.DS_CATEGORIA_GRUPPO,
     V_CONS_REGISTRO_INVENTARIO_BENI.DS_UBICAZIONE_BENE,
     V_CONS_REGISTRO_INVENTARIO_BENI.CD_ASSEGNATARIO,
     V_CONS_REGISTRO_INVENTARIO_BENI.DENOMINAZIONE_SEDE,
     V_CONS_REGISTRO_INVENTARIO_BENI.DATA_REGISTRAZIONE,
     V_CONS_REGISTRO_INVENTARIO_BENI.CD_TIPO_CARICO_SCARICO,
     V_CONS_REGISTRO_INVENTARIO_BENI.DS_TIPO_CARICO_SCARICO,
     V_CONS_REGISTRO_INVENTARIO_BENI.VARIAZIONE_PIU,
     V_CONS_REGISTRO_INVENTARIO_BENI.VARIAZIONE_MENO,
     V_CONS_REGISTRO_INVENTARIO_BENI.QUANTITA,
     V_CONS_REGISTRO_INVENTARIO_BENI.VALORE_UNITARIO,
     V_CONS_REGISTRO_INVENTARIO_BENI.IMPONIBILE_AMMORTAMENTO,
     V_CONS_REGISTRO_INVENTARIO_BENI.VALORE_AMMORTIZZATO,
     (NVL(AMMORTAMENTO_BENE_INV.IM_MOVIMENTO_AMMORT, 0)
        * NVL(INVENTARIO_UTILIZZATORI_LA.PERCENTUALE_UTILIZZO_CDR, 100) / 100
        * NVL(INVENTARIO_UTILIZZATORI_LA.PERCENTUALE_UTILIZZO_LA, 100) / 100)   IM_MOVIMENTO_AMMORT,
     AMMORTAMENTO_BENE_INV.NUMERO_ANNI,
     AMMORTAMENTO_BENE_INV.PERC_AMMORTAMENTO,
     AMMORTAMENTO_BENE_INV.PERC_PRIMO_ANNO,
     AMMORTAMENTO_BENE_INV.PERC_SUCCESSIVI,
     INVENTARIO_UTILIZZATORI_LA.CD_UTILIZZATORE_CDR,
     INVENTARIO_UTILIZZATORI_LA.CD_LINEA_ATTIVITA,
     INVENTARIO_UTILIZZATORI_LA.PERCENTUALE_UTILIZZO_CDR,
     INVENTARIO_UTILIZZATORI_LA.PERCENTUALE_UTILIZZO_LA,
     AMMORTAMENTO_BENE_INV.ESERCIZIO ESERCIZIO_AMM,
     V_CONS_REGISTRO_INVENTARIO_BENI.CD_UNITA_ASSEGNATARIO
 FROM V_CONS_REGISTRO_INVENTARIO_BENI
    LEFT JOIN AMMORTAMENTO_BENE_INV
    ON  AMMORTAMENTO_BENE_INV.PG_INVENTARIO = V_CONS_REGISTRO_INVENTARIO_BENI.PG_INVENTARIO
    AND AMMORTAMENTO_BENE_INV.NR_INVENTARIO = V_CONS_REGISTRO_INVENTARIO_BENI.NR_INVENTARIO
    AND AMMORTAMENTO_BENE_INV.PROGRESSIVO   = V_CONS_REGISTRO_INVENTARIO_BENI.PROGRESSIVO
    LEFT JOIN INVENTARIO_UTILIZZATORI_LA
    ON  INVENTARIO_UTILIZZATORI_LA.PG_INVENTARIO = V_CONS_REGISTRO_INVENTARIO_BENI.PG_INVENTARIO
    AND INVENTARIO_UTILIZZATORI_LA.NR_INVENTARIO = V_CONS_REGISTRO_INVENTARIO_BENI.NR_INVENTARIO
    AND INVENTARIO_UTILIZZATORI_LA.PROGRESSIVO   = V_CONS_REGISTRO_INVENTARIO_BENI.PROGRESSIVO;
