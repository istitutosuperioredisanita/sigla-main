  INVENTARIO_BENI
JOIN UBICAZIONE_BENE ON UBICAZIONE_BENE.CD_UBICAZIONE = INVENTARIO_BENI.CD_UBICAZIONE AND UBICAZIONE_BENE.CD_CDS = INVENTARIO_BENI.CD_CDS AND UBICAZIONE_BENE.CD_UNITA_ORGANIZZATIVA = INVENTARIO_BENI.CD_UNITA_ORGANIZZATIVA
