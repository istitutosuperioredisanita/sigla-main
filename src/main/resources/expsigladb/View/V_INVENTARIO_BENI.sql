SELECT
    INVENTARIO_BENI.PG_INVENTARIO,
    INVENTARIO_BENI.NR_INVENTARIO,
    INVENTARIO_BENI.PROGRESSIVO,
    INVENTARIO_BENI.DS_BENE,
    INVENTARIO_BENI.CD_CATEGORIA_GRUPPO,
    INVENTARIO_BENI.TI_AMMORTAMENTO,
    INVENTARIO_BENI.FL_AMMORTAMENTO,
    INVENTARIO_BENI.CD_CONDIZIONE_BENE,
    INVENTARIO_BENI.TI_COMMERCIALE_ISTITUZIONALE,
    INVENTARIO_BENI.VALORE_INIZIALE,
    INVENTARIO_BENI.VALORE_AMMORTIZZATO,
    INVENTARIO_BENI.VARIAZIONE_PIU,
    INVENTARIO_BENI.VARIAZIONE_MENO,
