LEFT JOIN ANAGRAFICO ON ANAGRAFICO.CD_ANAG = TERZO.CD_ANAG
LEFT JOIN UNITA_ORGANIZZATIVA UNITA_ORGANIZZATIVA_ASS ON UNITA_ORGANIZZATIVA_ASS.CD_UNITA_ORGANIZZATIVA = ANAGRAFICO.CD_UNITA_ORGANIZZATIVA;
