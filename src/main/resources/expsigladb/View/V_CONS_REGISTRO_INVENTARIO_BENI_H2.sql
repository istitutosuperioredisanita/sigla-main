-- SIGLASVILUPPO.V_CONS_REGISTRO_INVENTARIO_BENI source

CREATE OR REPLACE FORCE VIEW "V_CONS_REGISTRO_INVENTARIO_BENI" ("PG_INVENTARIO", "TI_DOCUMENTO", "ESERCIZIO", "PG_BUONO_C_S", "NR_INVENTARIO", "PROGRESSIVO", "CD_UNITA_ORGANIZZATIVA", "CD_CDS", "ESERCIZIO_CARICO_BENE", "ETICHETTA", "DS_BENE", "FL_TOTALMENTE_SCARICATO", "FL_DISMESSO", "DT_DISMESSO", "FL_BENE_IN_IST", "FL_MIGRATO", "VALORE_INIZIALE", "CATEGORIA", "CD_CATEGORIA_GRUPPO", "DS_CATEGORIA_GRUPPO", "DS_UBICAZIONE_BENE", "CD_ASSEGNATARIO", "DENOMINAZIONE_SEDE", "DATA_REGISTRAZIONE", "CD_TIPO_CARICO_SCARICO", "DS_TIPO_CARICO_SCARICO", "VARIAZIONE_PIU", "VARIAZIONE_MENO", "QUANTITA", "VALORE_UNITARIO", "IMPONIBILE_AMMORTAMENTO", "VALORE_AMMORTIZZATO", "CD_UNITA_ASSEGNATARIO") AS
  SELECT
    INVENTARIO_BENI.PG_INVENTARIO,
    'C' TI_DOCUMENTO,
    INVENTARIO_BENI.ESERCIZIO_CARICO_BENE ESERCIZIO,
    NULL PG_BUONO_C_S,
    INVENTARIO_BENI.NR_INVENTARIO,
    INVENTARIO_BENI.PROGRESSIVO,
    INVENTARIO_BENI.CD_UNITA_ORGANIZZATIVA,
    INVENTARIO_BENI.CD_CDS,
    INVENTARIO_BENI.ESERCIZIO_CARICO_BENE,
    INVENTARIO_BENI.ETICHETTA,
    INVENTARIO_BENI.DS_BENE,
    INVENTARIO_BENI.FL_TOTALMENTE_SCARICATO,
    INVENTARIO_BENI.FL_DISMESSO,
    INVENTARIO_BENI.DT_DISMESSO,
    INVENTARIO_BENI.FL_BENE_IN_IST,
    INVENTARIO_BENI.FL_MIGRATO,
    -- VALORE_INIZIALE
    INVENTARIO_BENI.VALORE_INIZIALE,
    CATEGORIA_GRUPPO_INVENT.CD_CATEGORIA_PADRE                                 CATEGORIA,
    INVENTARIO_BENI.CD_CATEGORIA_GRUPPO,
    CATEGORIA_GRUPPO_INVENT.DS_CATEGORIA_GRUPPO,
    UBICAZIONE_BENE.DS_UBICAZIONE_BENE,
    INVENTARIO_BENI.CD_ASSEGNATARIO,
    TERZO.DENOMINAZIONE_SEDE,
    INVENTARIO_BENI.DT_ACQUISIZIONE DATA_REGISTRAZIONE,
    NULL CD_TIPO_CARICO_SCARICO,
    NULL DS_TIPO_CARICO_SCARICO,
    0 VARIAZIONE_PIU,
    0 VARIAZIONE_MENO,
    0 QUANTITA,
    0 VALORE_UNITARIO,
    NVL(INVENTARIO_BENI.IMPONIBILE_AMMORTAMENTO, 0)                            IMPONIBILE_AMMORTAMENTO,
    INVENTARIO_BENI.VALORE_AMMORTIZZATO,
    ANAGRAFICO_ASSEGNATARIO.CD_UNITA_ORGANIZZATIVA                             CD_UNITA_ASSEGNATARIO
FROM INVENTARIO_BENI
     JOIN UBICAZIONE_BENE
       ON  UBICAZIONE_BENE.CD_CDS                  = INVENTARIO_BENI.CD_CDS
       AND UBICAZIONE_BENE.CD_UNITA_ORGANIZZATIVA  = INVENTARIO_BENI.CD_UNITA_ORGANIZZATIVA
       AND UBICAZIONE_BENE.CD_UBICAZIONE           = INVENTARIO_BENI.CD_UBICAZIONE
     JOIN CATEGORIA_GRUPPO_INVENT
       ON  CATEGORIA_GRUPPO_INVENT.CD_CATEGORIA_GRUPPO = INVENTARIO_BENI.CD_CATEGORIA_GRUPPO
     JOIN TERZO
       ON  TERZO.CD_UNITA_ORGANIZZATIVA = INVENTARIO_BENI.CD_UNITA_ORGANIZZATIVA
       AND TERZO.CD_TERZO IN (SELECT MIN(t.CD_TERZO)
                                FROM TERZO t
                               WHERE t.CD_UNITA_ORGANIZZATIVA = INVENTARIO_BENI.CD_UNITA_ORGANIZZATIVA
                                 AND t.DT_FINE_RAPPORTO IS NULL)
     LEFT JOIN TERZO TERZO_ASSEGNATARIO
       ON  TERZO_ASSEGNATARIO.CD_TERZO = INVENTARIO_BENI.CD_ASSEGNATARIO
     LEFT JOIN ANAGRAFICO ANAGRAFICO_ASSEGNATARIO
       ON  ANAGRAFICO_ASSEGNATARIO.CD_ANAG = TERZO_ASSEGNATARIO.CD_ANAG
WHERE NOT EXISTS(SELECT '1' FROM BUONO_CARICO_SCARICO_DETT
			     JOIN BUONO_CARICO_SCARICO
			       ON  BUONO_CARICO_SCARICO.PG_INVENTARIO = BUONO_CARICO_SCARICO_DETT.PG_INVENTARIO
			       AND BUONO_CARICO_SCARICO.TI_DOCUMENTO  = BUONO_CARICO_SCARICO_DETT.TI_DOCUMENTO
			       AND BUONO_CARICO_SCARICO.ESERCIZIO     = BUONO_CARICO_SCARICO_DETT.ESERCIZIO
			       AND BUONO_CARICO_SCARICO.PG_BUONO_C_S  = BUONO_CARICO_SCARICO_DETT.PG_BUONO_C_S
			     JOIN TIPO_CARICO_SCARICO
			       ON  TIPO_CARICO_SCARICO.CD_TIPO_CARICO_SCARICO = BUONO_CARICO_SCARICO.CD_TIPO_CARICO_SCARICO
                 WHERE BUONO_CARICO_SCARICO_DETT.PG_INVENTARIO = INVENTARIO_BENI.PG_INVENTARIO
			     AND BUONO_CARICO_SCARICO_DETT.NR_INVENTARIO = INVENTARIO_BENI.NR_INVENTARIO
			     AND BUONO_CARICO_SCARICO_DETT.PROGRESSIVO   = INVENTARIO_BENI.PROGRESSIVO
			     AND TIPO_CARICO_SCARICO.FL_AUMENTO_VALORE = 'N')
UNION ALL
  SELECT
    INVENTARIO_BENI.PG_INVENTARIO,
    BUONO_CARICO_SCARICO_DETT.TI_DOCUMENTO,
    BUONO_CARICO_SCARICO_DETT.ESERCIZIO,
    BUONO_CARICO_SCARICO_DETT.PG_BUONO_C_S,
    INVENTARIO_BENI.NR_INVENTARIO,
    INVENTARIO_BENI.PROGRESSIVO,
    INVENTARIO_BENI.CD_UNITA_ORGANIZZATIVA,
    INVENTARIO_BENI.CD_CDS,
    INVENTARIO_BENI.ESERCIZIO_CARICO_BENE,
    INVENTARIO_BENI.ETICHETTA,
    INVENTARIO_BENI.DS_BENE,
    INVENTARIO_BENI.FL_TOTALMENTE_SCARICATO,
    INVENTARIO_BENI.FL_DISMESSO,
    INVENTARIO_BENI.DT_DISMESSO,
    INVENTARIO_BENI.FL_BENE_IN_IST,
    INVENTARIO_BENI.FL_MIGRATO,
    -- VALORE_INIZIALE
    CASE
      WHEN BUONO_CARICO_SCARICO_DETT.TI_DOCUMENTO = 'C'
       AND TIPO_CARICO_SCARICO.FL_AUMENTO_VALORE = 'N'
   	   AND (BUONO_CARICO_SCARICO_DETT.ESERCIZIO, BUONO_CARICO_SCARICO_DETT.PG_BUONO_C_S) =
	       (SELECT MIN(dett.ESERCIZIO),
	               MIN(dett.PG_BUONO_C_S) KEEP (DENSE_RANK FIRST ORDER BY dett.ESERCIZIO, dett.PG_BUONO_C_S)
	          FROM BUONO_CARICO_SCARICO_DETT dett
	          LEFT JOIN BUONO_CARICO_SCARICO bcs
	                 ON bcs.PG_INVENTARIO = dett.PG_INVENTARIO
	                AND bcs.TI_DOCUMENTO  = dett.TI_DOCUMENTO
	                AND bcs.ESERCIZIO     = dett.ESERCIZIO
	                AND bcs.PG_BUONO_C_S  = dett.PG_BUONO_C_S
	          LEFT JOIN TIPO_CARICO_SCARICO tcs
	                 ON tcs.CD_TIPO_CARICO_SCARICO = bcs.CD_TIPO_CARICO_SCARICO
	         WHERE dett.TI_DOCUMENTO = 'C'
	           AND tcs.FL_AUMENTO_VALORE = 'N'
	           AND dett.PG_INVENTARIO = INVENTARIO_BENI.PG_INVENTARIO
	           AND dett.NR_INVENTARIO = INVENTARIO_BENI.NR_INVENTARIO
	           AND dett.PROGRESSIVO   = INVENTARIO_BENI.PROGRESSIVO)
        THEN BUONO_CARICO_SCARICO_DETT.VALORE_UNITARIO
      ELSE 0
    END                                                                        VALORE_INIZIALE,
    CATEGORIA_GRUPPO_INVENT.CD_CATEGORIA_PADRE                                 CATEGORIA,
    INVENTARIO_BENI.CD_CATEGORIA_GRUPPO,
    CATEGORIA_GRUPPO_INVENT.DS_CATEGORIA_GRUPPO,
    UBICAZIONE_BENE.DS_UBICAZIONE_BENE,
    INVENTARIO_BENI.CD_ASSEGNATARIO,
    TERZO.DENOMINAZIONE_SEDE,
    BUONO_CARICO_SCARICO.DATA_REGISTRAZIONE,
    TIPO_CARICO_SCARICO.CD_TIPO_CARICO_SCARICO,
    TIPO_CARICO_SCARICO.DS_TIPO_CARICO_SCARICO,
    -- VARIAZIONE_PIU
    CASE
      WHEN BUONO_CARICO_SCARICO_DETT.TI_DOCUMENTO = 'C'
       AND TIPO_CARICO_SCARICO.FL_AUMENTO_VALORE = 'Y'
        THEN BUONO_CARICO_SCARICO_DETT.VALORE_UNITARIO
      ELSE 0
    END                                                                        VARIAZIONE_PIU,
    -- VARIAZIONE_MENO
    CASE
      WHEN BUONO_CARICO_SCARICO_DETT.PG_BUONO_C_S IS NULL
        THEN NVL(INVENTARIO_BENI.VARIAZIONE_MENO, 0)
      WHEN BUONO_CARICO_SCARICO_DETT.TI_DOCUMENTO = 'S'
        THEN BUONO_CARICO_SCARICO_DETT.VALORE_UNITARIO
      ELSE 0
    END                                                                        VARIAZIONE_MENO,
    BUONO_CARICO_SCARICO_DETT.QUANTITA,
    BUONO_CARICO_SCARICO_DETT.VALORE_UNITARIO,
    NVL(INVENTARIO_BENI.IMPONIBILE_AMMORTAMENTO, 0)                            IMPONIBILE_AMMORTAMENTO,
    INVENTARIO_BENI.VALORE_AMMORTIZZATO,
    ANAGRAFICO_ASSEGNATARIO.CD_UNITA_ORGANIZZATIVA                             CD_UNITA_ASSEGNATARIO
FROM INVENTARIO_BENI
     JOIN UBICAZIONE_BENE
       ON  UBICAZIONE_BENE.CD_CDS                  = INVENTARIO_BENI.CD_CDS
       AND UBICAZIONE_BENE.CD_UNITA_ORGANIZZATIVA  = INVENTARIO_BENI.CD_UNITA_ORGANIZZATIVA
       AND UBICAZIONE_BENE.CD_UBICAZIONE           = INVENTARIO_BENI.CD_UBICAZIONE
     JOIN CATEGORIA_GRUPPO_INVENT
       ON  CATEGORIA_GRUPPO_INVENT.CD_CATEGORIA_GRUPPO = INVENTARIO_BENI.CD_CATEGORIA_GRUPPO
     JOIN TERZO
       ON  TERZO.CD_UNITA_ORGANIZZATIVA = INVENTARIO_BENI.CD_UNITA_ORGANIZZATIVA
       AND TERZO.CD_TERZO IN (SELECT MIN(t.CD_TERZO)
                                FROM TERZO t
                               WHERE t.CD_UNITA_ORGANIZZATIVA = INVENTARIO_BENI.CD_UNITA_ORGANIZZATIVA
                                 AND t.DT_FINE_RAPPORTO IS NULL)
     -- OUTER JOIN richiesto: movimenti di carico/scarico
     JOIN BUONO_CARICO_SCARICO_DETT
       ON  BUONO_CARICO_SCARICO_DETT.PG_INVENTARIO = INVENTARIO_BENI.PG_INVENTARIO
       AND BUONO_CARICO_SCARICO_DETT.NR_INVENTARIO = INVENTARIO_BENI.NR_INVENTARIO
       AND BUONO_CARICO_SCARICO_DETT.PROGRESSIVO   = INVENTARIO_BENI.PROGRESSIVO
     JOIN BUONO_CARICO_SCARICO
       ON  BUONO_CARICO_SCARICO.PG_INVENTARIO = BUONO_CARICO_SCARICO_DETT.PG_INVENTARIO
       AND BUONO_CARICO_SCARICO.TI_DOCUMENTO  = BUONO_CARICO_SCARICO_DETT.TI_DOCUMENTO
       AND BUONO_CARICO_SCARICO.ESERCIZIO     = BUONO_CARICO_SCARICO_DETT.ESERCIZIO
       AND BUONO_CARICO_SCARICO.PG_BUONO_C_S  = BUONO_CARICO_SCARICO_DETT.PG_BUONO_C_S
     JOIN TIPO_CARICO_SCARICO
       ON  TIPO_CARICO_SCARICO.CD_TIPO_CARICO_SCARICO = BUONO_CARICO_SCARICO.CD_TIPO_CARICO_SCARICO
     LEFT JOIN TERZO TERZO_ASSEGNATARIO
       ON  TERZO_ASSEGNATARIO.CD_TERZO = INVENTARIO_BENI.CD_ASSEGNATARIO
     LEFT JOIN ANAGRAFICO ANAGRAFICO_ASSEGNATARIO
       ON  ANAGRAFICO_ASSEGNATARIO.CD_ANAG = TERZO_ASSEGNATARIO.CD_ANAG;
